# 模型判定“知识库未收录”时的特征短语（模型输出格式可能不完全受控，用模糊匹配兜底）
UNMATCHED_MARKERS = (
    "【知识库未收录】",
    "知识库未收录",
    "知识库中暂无相关内容",
    "知识库暂无相关内容",
    "知识库中未收录",
    "知识库未覆盖",
)


def is_unmatched_answer(answer: str) -> bool:
    """判断模型回答是否属于"知识库未收录"拒答（前 40 字内出现特征短语即判定）。"""
    head = (answer or "").strip()[:40]
    return any(m in head for m in UNMATCHED_MARKERS)


